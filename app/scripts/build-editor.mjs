// Bundles the page editor (src/editor/native-entry.ts and everything it
// imports) into one self-contained HTML page for the Android app's WebView,
// written as a string to src/editor/editorHtml.generated.ts. Run it after
// changing anything under src/editor/ (npm run build:editor); the web build
// doesn't need it, since it imports core.ts directly.
import {mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'vite';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = mkdtempSync(join(tmpdir(), 'sp-editor-'));
try {
  await build({
    configFile: false,
    logLevel: 'warn',
    root: app,
    build: {
      outDir: out,
      emptyOutDir: true,
      minify: true,
      lib: {entry: join(app, 'src/editor/native-entry.ts'), formats: ['iife'], name: 'SuperPagesEditor', fileName: () => 'editor.js'},
    },
  });
  const js = readFileSync(join(out, readdirSync(out).find(f => f.endsWith('.js'))), 'utf8');
  const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; img-src data:; style-src 'unsafe-inline'; script-src 'unsafe-inline'">
<style>html,body,#root{margin:0;height:100%;}body{overscroll-behavior:none;}</style>
</head><body><div id="root"></div><script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;
  writeFileSync(
    join(app, 'src/editor/editorHtml.generated.ts'),
    `// Generated by scripts/build-editor.mjs from src/editor/. Don't edit by hand.\n/* eslint-disable */\nexport const EDITOR_HTML = ${JSON.stringify(html)};\n`,
  );
  console.log(`editor bundle: ${(html.length / 1024).toFixed(0)} KB`);
} finally {
  rmSync(out, {recursive: true, force: true});
}
