const pick = (list: string[]) => list[Math.floor(Math.random() * list.length)];

export function randomSlug(): string {
  return `${pick(ADJECTIVES)}-${pick(ANIMALS)}`;
}

/** What the server takes: 3–48 lowercase letters and numbers, single dashes between. */
export const SLUG_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

export function validSlug(s: string): boolean {
  return s.length >= 3 && s.length <= 48 && SLUG_RE.test(s);
}

/** Turns what's typed into a slug: lowercase, spaces and stray marks to dashes. */
export function cleanSlug(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/-{2,}/g, '-')
    .replace(/^-/, '')
    .slice(0, 48);
}
